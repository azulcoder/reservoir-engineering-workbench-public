def canonical_hash(payload: Any) -> str:
    """Return a stable digest of a JSON-serialisable payload."""
    return hashlib.sha256(
        json.dumps(payload, sort_keys=True, separators=(",", ":"), default=repr).encode()
    ).hexdigest()


def t_d(hours: float) -> float:
    """Dimensionless time at the declared properties."""
    return dimensionless_time(
        hours,
        permeability_md=TRUTH["permeability_md"],
        porosity=TRUTH["porosity"],
        viscosity_cp=TRUTH["viscosity_cp"],
        total_compressibility_per_psi=TRUTH["total_compressibility_per_psi"],
        wellbore_radius_ft=TRUTH["wellbore_radius_ft"],
    )


def hours_at_t_d(target: float) -> float:
    """Elapsed time in hours at which dimensionless time reaches ``target``."""
    return (
        target
        * TRUTH["porosity"]
        * TRUTH["viscosity_cp"]
        * TRUTH["total_compressibility_per_psi"]
        * TRUTH["wellbore_radius_ft"] ** 2
    ) / (0.0002637 * TRUTH["permeability_md"])


def drawdown_psi(hours: float) -> float:
    """Return the synthetic observation: drawdown from initial pressure, in psi."""
    return pressure_drop_psi(
        line_source_dimensionless_pressure(t_d(hours), skin=TRUTH["skin"]),
        permeability_md=TRUTH["permeability_md"],
        thickness_ft=TRUTH["thickness_ft"],
        rate_stb_per_day=TRUTH["rate_stb_per_day"],
        formation_volume_factor=TRUTH["formation_volume_factor"],
        viscosity_cp=TRUTH["viscosity_cp"],
    )


def log_window(first: float, last: float, per_decade: int) -> list[float]:
    """Return logarithmically spaced times, inclusive of both ends."""
    decades = math.log10(last) - math.log10(first)
    count = max(3, round(per_decade * decades) + 1)
    return [10 ** (math.log10(first) + i * decades / (count - 1)) for i in range(count)]


def interpret(times: list[float], drops: list[float]) -> Any:
    """Run the blind semilog interpretation at the declared well and fluid properties."""
    return semilog_interpretation(
        times,
        drops,
        thickness_ft=TRUTH["thickness_ft"],
        rate_stb_per_day=TRUTH["rate_stb_per_day"],
        formation_volume_factor=TRUTH["formation_volume_factor"],
        viscosity_cp=TRUTH["viscosity_cp"],
        porosity=TRUTH["porosity"],
        total_compressibility_per_psi=TRUTH["total_compressibility_per_psi"],
        wellbore_radius_ft=TRUTH["wellbore_radius_ft"],
    )


def recovery_errors(fit: Any) -> tuple[float, float]:
    """Return ``(relative kh error, absolute skin error)`` against the declared truth."""
    kh_true = TRUTH["permeability_md"] * TRUTH["thickness_ft"]
    return (
        abs(fit.permeability_thickness_md_ft - kh_true) / kh_true,
        abs(fit.skin - TRUTH["skin"]),
    )


# ---------------------------------------------------------------------------------
# B1.0 -- mathematical baseline
# ---------------------------------------------------------------------------------
def experiment_b1_0() -> dict[str, Any]:
    """Noise-free recovery over the declared window, plus the forward and constant checks."""
    # C2: every published field constant, recomputed.
    # Each published constant is compared at the precision it is actually printed to.
    # A single relative tolerance is the wrong instrument here: 162.6 carries four
    # significant figures and 3.2275 carries five, so one tolerance is either too loose
    # for one or too tight for the other. The literature also truncates as often as it
    # rounds -- 0.80907 is a truncation of 0.8090787, which rounds to 0.80908 -- so the
    # test is agreement within one unit in the last printed digit, which both a rounded
    # and a truncated form satisfy and a genuinely wrong constant does not.
    constants = (
        ("line_source_0_80907", LINE_SOURCE_CONSTANT, "0.80907"),
        ("semilog_slope_162_6", semilog_slope_constant(), "162.6"),
        ("derivative_plateau_70_6", derivative_plateau_constant(), "70.6"),
        ("skin_3_2275", semilog_skin_constant(), "3.2275"),
    )
    constant_rows = []
    for name, derived, printed in constants:
        decimals = len(printed.split(".")[1]) if "." in printed else 0
        last_digit_unit = 10.0**-decimals
        difference = abs(derived - float(printed))
        constant_rows.append(
            {
                "name": name,
                "derived": derived,
                "published_as_printed": printed,
                "printed_decimals": decimals,
                "last_digit_unit": last_digit_unit,
                "absolute_difference": difference,
                "within_published_precision": difference <= last_digit_unit,
            }
        )

    # C1: the forward solution against the arbitrary-precision oracle, in B1's own range.
    oracle_rows = []
    for hours in (1.0, 4.0, 12.0, 24.0, 48.0):
        argument = 1.0 / (4.0 * t_d(hours))
        oracle_rows.append(
            {
                "time_hours": hours,
                "dimensionless_time": t_d(hours),
                "e1_argument": argument,
                "e1_float": exponential_integral_e1(argument),
                "e1_high_precision": _e1_high_precision(argument),
                "relative_difference": abs(exponential_integral_e1(argument) - _e1_high_precision(argument))
                / abs(_e1_high_precision(argument)),
            }
        )

    times = log_window(WINDOW_FIRST_HOUR, WINDOW_LAST_HOUR, BASE_POINTS_PER_DECADE)
    drops = [drawdown_psi(t) for t in times]
    fit = interpret(times, drops)
    kh_error, skin_error = recovery_errors(fit)

    # C5 and C6: the Bourdet derivative against the closed form, and against 1/2.
    scale = pressure_drop_psi(
        1.0,
        permeability_md=TRUTH["permeability_md"],
        thickness_ft=TRUTH["thickness_ft"],
        rate_stb_per_day=TRUTH["rate_stb_per_day"],
        formation_volume_factor=TRUTH["formation_volume_factor"],
        viscosity_cp=TRUTH["viscosity_cp"],
    )
    deriv_times, deriv_values = bourdet_derivative(times, drops, smoothing_l=SMOOTHING_L)
    analytic = [line_source_log_derivative(t_d(t)) * scale for t in deriv_times]
    derivative_errors = [abs(d - a) / a for d, a in zip(deriv_values, analytic, strict=True)]
    ideal_plateau = 0.5 * scale
    plateau_deficits = [(ideal_plateau - d) / ideal_plateau for d in deriv_values]

    return {
        "window": {
            "first_hour": WINDOW_FIRST_HOUR,
            "last_hour": WINDOW_LAST_HOUR,
            "first_dimensionless_time": t_d(WINDOW_FIRST_HOUR),
            "last_dimensionless_time": t_d(WINDOW_LAST_HOUR),
            "points_per_decade": BASE_POINTS_PER_DECADE,
            "points": len(times),
        },
        "derived_constants": constant_rows,
        "forward_against_oracle": oracle_rows,
        "max_forward_relative_difference": max(r["relative_difference"] for r in oracle_rows),
        "fit": {
            "slope_psi_per_cycle": fit.slope_psi_per_cycle,
            "intercept_psi": fit.intercept_psi,
            "pressure_drop_at_one_hour_psi": fit.pressure_drop_at_one_hour,
            "r_squared": fit.r_squared,
            "residual_standard_error_psi": fit.residual_standard_error_psi,
        },
        "recovery": {
            "permeability_md_true": TRUTH["permeability_md"],
            "permeability_md_recovered": fit.permeability_md,
            "permeability_thickness_true": TRUTH["permeability_md"] * TRUTH["thickness_ft"],
            "permeability_thickness_recovered": fit.permeability_thickness_md_ft,
            "permeability_thickness_relative_error": kh_error,
            "skin_true": TRUTH["skin"],
            "skin_recovered": fit.skin,
            "skin_absolute_error": skin_error,
        },
        "derivative": {
            "smoothing_l": SMOOTHING_L,
            "points": len(deriv_values),
            "max_relative_error_against_closed_form": max(derivative_errors),
            "median_relative_error_against_closed_form": statistics.median(derivative_errors),
            "ideal_plateau_psi": ideal_plateau,
            "mean_measured_plateau_psi": statistics.fmean(deriv_values),
            "max_deficit_from_ideal_relative": max(plateau_deficits),
            "min_deficit_from_ideal_relative": min(plateau_deficits),
            "all_below_ideal": all(d < ideal_plateau for d in deriv_values),
        },
        "c1_forward_matches_oracle": max(r["relative_difference"] for r in oracle_rows)
        <= C1_FORWARD_ORACLE_RELATIVE,
        "c2_constants_reproduce": all(r["within_published_precision"] for r in constant_rows),
        "c3_kh_recovered": kh_error <= C3_KH_RELATIVE,
        "c4_skin_recovered": skin_error <= C4_SKIN_ABSOLUTE,
        "c5_derivative_matches_closed_form": max(derivative_errors) <= C5_DERIVATIVE_RELATIVE,
        "c6_plateau_below_ideal_half": all(d < ideal_plateau for d in deriv_values),
    }


def _e1_high_precision(x: float, digits: int = 40) -> float:
    """Oracle O1. Declared valid for x <= 2, which contains the whole B1 window."""
    from decimal import Decimal, getcontext

    if x > 2.0:
        raise ValueError("oracle O1 is declared valid only for x <= 2")
    getcontext().prec = digits + 25
    value = Decimal(repr(x))
    gamma = Decimal("0.5772156649015328606065120900824024310421593359399235988057672348849")
    total = Decimal(0)
    term = Decimal(1)
    for n in range(1, 400):
        term *= -value / n
        total += -term / n
        if abs(term / n) < Decimal(10) ** (-(digits + 15)):
            break
    return float(-gamma - value.ln() + total)


# ---------------------------------------------------------------------------------
# B1.1 -- sampling density and window placement
# ---------------------------------------------------------------------------------
def experiment_b1_1() -> dict[str, Any]:
    """Which of point density and window placement actually limits a clean interpretation."""
    density_rows = []
    for per_decade in SAMPLING_POINTS_PER_DECADE:
        times = log_window(WINDOW_FIRST_HOUR, WINDOW_LAST_HOUR, per_decade)
        fit = interpret(times, [drawdown_psi(t) for t in times])
        kh_error, skin_error = recovery_errors(fit)
        density_rows.append(
            {
                "points_per_decade": per_decade,
                "points": len(times),
                "permeability_thickness_relative_error": kh_error,
                "skin_absolute_error": skin_error,
            }
        )

    placement_rows = []
    for start_t_d in WINDOW_START_T_D:
        first = hours_at_t_d(start_t_d)
        last = first * (WINDOW_LAST_HOUR / WINDOW_FIRST_HOUR)
        times = log_window(first, last, BASE_POINTS_PER_DECADE)
        fit = interpret(times, [drawdown_psi(t) for t in times])
        kh_error, skin_error = recovery_errors(fit)
        placement_rows.append(
            {
                "window_start_dimensionless_time": start_t_d,
                "first_hour": first,
                "last_hour": last,
                "permeability_thickness_relative_error": kh_error,
                "skin_absolute_error": skin_error,
                # The protocol predicted this scale before the run.
                "predicted_bias_one_over_ten_t_d": 1.0 / (10.0 * start_t_d),
            }
        )

    density_spread = max(r["permeability_thickness_relative_error"] for r in density_rows) / min(
        r["permeability_thickness_relative_error"] for r in density_rows
    )
    placement_spread = max(r["permeability_thickness_relative_error"] for r in placement_rows) / min(
        r["permeability_thickness_relative_error"] for r in placement_rows
    )
    return {
        "density_sweep": density_rows,
        "placement_sweep": placement_rows,
        "density_error_spread_ratio": density_spread,
        "placement_error_spread_ratio": placement_spread,
        "placement_dominates": placement_spread > density_spread,
    }


# ---------------------------------------------------------------------------------
# B1.2 -- pressure noise
# ---------------------------------------------------------------------------------
def experiment_b1_2() -> dict[str, Any]:
    """Degradation under additive Gaussian pressure error, over fixed seeds."""
    times = log_window(WINDOW_FIRST_HOUR, WINDOW_LAST_HOUR, BASE_POINTS_PER_DECADE)
    clean = [drawdown_psi(t) for t in times]
    rows = []
    for sigma in NOISE_SIGMAS_PSI:
        kh_errors: list[float] = []
        skin_errors: list[float] = []
        for replicate in range(NOISE_REPLICATES):
            rng = random.Random(NOISE_SEED_BASE + replicate)
            noisy = [value + rng.gauss(0.0, sigma) for value in clean]
            fit = interpret(times, noisy)
            kh_error, skin_error = recovery_errors(fit)
            kh_errors.append(kh_error)
            skin_errors.append(skin_error)
        kh_sorted = sorted(kh_errors)
        skin_sorted = sorted(skin_errors)
        p95 = int(0.95 * (NOISE_REPLICATES - 1))
        rows.append(
            {
                "sigma_psi": sigma,
                "replicates": NOISE_REPLICATES,
                "seed_base": NOISE_SEED_BASE,
                "kh_relative_error_mean": statistics.fmean(kh_errors),
                "kh_relative_error_p95": kh_sorted[p95],
                # Monte Carlo standard error of the mean, which is a property of the
                # replicate count and not an uncertainty about the reservoir.
                "kh_relative_error_monte_carlo_se": statistics.stdev(kh_errors) / math.sqrt(NOISE_REPLICATES),
                "skin_absolute_error_mean": statistics.fmean(skin_errors),
                "skin_absolute_error_p95": skin_sorted[p95],
                "skin_absolute_error_monte_carlo_se": statistics.stdev(skin_errors)
                / math.sqrt(NOISE_REPLICATES),
            }
        )
    means = [r["kh_relative_error_mean"] for r in rows]
    return {
        "noise_model": "additive, independent, zero-mean Gaussian error on pressure only",
        "signal_for_scale": {
            "drawdown_across_window_psi": clean[-1] - clean[0],
            "semilog_slope_psi_per_cycle": interpret(times, clean).slope_psi_per_cycle,
        },
        "levels": rows,
        "c9_monotone_in_sigma": means == sorted(means),
    }


