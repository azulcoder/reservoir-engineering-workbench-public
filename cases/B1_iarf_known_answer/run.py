def experiment_b1_3() -> dict[str, Any]:
    """Apply the same interpretation where the semilog approximation is invalid."""
    first = hours_at_t_d(NEGATIVE_CONTROL_T_D[0])
    last = hours_at_t_d(NEGATIVE_CONTROL_T_D[1])
    times = log_window(first, last, BASE_POINTS_PER_DECADE)
    drops = [drawdown_psi(t) for t in times]
    fit = interpret(times, drops)
    kh_error, skin_error = recovery_errors(fit)
    return {
        "window_dimensionless_time": list(NEGATIVE_CONTROL_T_D),
        "first_hour": first,
        "last_hour": last,
        "points": len(times),
        "recovery": {
            "permeability_md_recovered": fit.permeability_md,
            "permeability_thickness_relative_error": kh_error,
            "skin_recovered": fit.skin,
            "skin_absolute_error": skin_error,
        },
        # The point of the control: the fit still looks excellent.
        "r_squared": fit.r_squared,
        "residual_standard_error_psi": fit.residual_standard_error_psi,
        "looks_like_a_good_fit": fit.r_squared > 0.999,
        "c7_negative_control_fails_c3": kh_error > C7_NEGATIVE_CONTROL_MIN_KH_ERROR,
        "also_misses_the_looser_plan_target_of_five_percent": kh_error > 0.05,
    }


