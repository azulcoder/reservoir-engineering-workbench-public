"""Case B1 -- infinite-acting radial flow, known answer.

Runs the four experiments pre-registered in ``protocol.md``, which was committed before
this file existed. Nothing here chooses a threshold: every acceptance number is copied
from the protocol and is checked against results it was written before.

    PYTHONPATH=src python3 cases/B1_iarf_known_answer/run.py --out artifacts/B1_iarf_known_answer/run-001

The study is the transient analogue of A1. A synthetic drawdown is generated from the
line-source solution at declared properties, and a semilog straight line is asked to
recover the permeability and skin that generated it. The generator evaluates a special
function; the interpreter fits a line on a logarithmic axis and is never told the
answer. Where they agree, the agreement is evidence about the instrument. Where the
interpreter is pointed outside its valid window it is expected to fail, and B1.3 exists
to show the acceptance machinery refusing a result that still looks like a straight line.
"""

